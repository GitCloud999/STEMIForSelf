package com.stemi.dataClasses;

public class SagittaData {
    private double sagittaMv;
    private int code;
    private boolean tombStoneFlag;

    public double getSagittaMv() {
        return sagittaMv;
    }

    public void setSagittaMv(double sagittaMv) {
        this.sagittaMv = sagittaMv;
    }

    public int getCode() {
        return code;
    }

    public void setCode(int code) {
        this.code = code;
    }

    public boolean getTombStoneFlag() {
        return tombStoneFlag;
    }

    public void setTombStoneFlag(boolean tombStoneFlag) {
        this.tombStoneFlag = tombStoneFlag;
    }

}
